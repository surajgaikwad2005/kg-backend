/**
 * domain-configuration/common/contextService.js
 * The CDM "context" staging layer — review extracted rows for any connector,
 * commit them to the database. Row-level PATCH edits (patchPnidRows/
 * patchSapRows), file-serve (getPnidFile), and SAP-joins GET/PUT
 * (getSapJoins/updateSapJoins) were removed entirely (2026-07-20) — zero
 * consumers anywhere in the app.
 *
 * Spec: Context router — backend paths are flat action names under /context/*
 * (e.g. /context/get, /context/commit), not a nested REST shape. Verified
 * live against refactored_apis_data/Domain_Configuration/Decision Context/*.md
 * (generated by api-doc-gen.mjs from the real backend, not hand-derived from
 * the spec alone).
 *
 * Reads AND commits for ALL FOUR connectors (pnid | documents | sap |
 * timeseries) now go through the two unified functions below —
 * getContext()/commitContext() — see their own doc comments. The legacy
 * per-connector functions (getPnidContext/getSapContext/getDocsContext/
 * getTsContext, commitPnidContext/commitDocsContext/commitTsContext/
 * commitSapContext) were removed from this app (2026-08-13): the backend
 * keeps those endpoints alive, but this app no longer calls them. See
 * api-data/domain-configuration-context.json.
 *
 * The context router wraps every response in {success, message, data};
 * unwrap() strips that envelope so callers keep working with the flat
 * payload — it's a no-op if a given response isn't wrapped.
 */
import { apiClient } from '../../apiClient';

const unwrap = (res) => (res && typeof res === 'object' && 'data' in res && 'success' in res) ? res.data : res;

// ── Read (unified) ───────────────────────────────────────────────────────────
/**
 * Review staged context rows for any connector through the single unified
 * context router — `GET /context/get`. Replaces the four per-connector read
 * endpoints (getPnidContext/getSapContext/getDocsContext/getTsContext); the
 * backend keeps those alive but this app now reads exclusively through this
 * one path, with `connector` selecting which internal flow runs.
 *
 * `connector`: 'pnid' | 'documents' | 'sap' | 'timeseries' | 'aif' | 'gloc' | 'lopc'.
 * 2026-08-17 update: the endpoint now serves all seven connectors (previously
 * four) — 'aif'/'gloc'/'lopc' are the SAP-linked findings feeds that moved to
 * their own native connector value on the upload side too (see
 * connectorsService.js's 2026-08-17 note + admin.constants.js FEED_TYPES). No
 * review screen consumes these three through this endpoint yet (see
 * useSourceTabs.js — FEED_TYPES rows have no `tabView`), so only the
 * connector/param support is wired here; add a query hook in useDsiQueries.js
 * + a key in src/lib/query/keys.js when a findings review screen is built.
 *
 * Per-connector param support (confirmed live, see
 * api-data/domain-configuration-context.json): pnid needs `files` +
 * `batchId` (+ optional `jobId`); documents needs `files` + `docTypes` +
 * `batchId` (+ optional `jobId`) + pagination; timeseries needs `sourceFile`
 * + `batchId` + pagination; sap needs `table` + pagination (no batchId);
 * aif/gloc/lopc need pagination + optional `unmatchedOnly` (no batchId/files
 * — confirmed live via `GET /context/get?connector=lopc&unmatched_only=true`,
 * see api-data/domain-configuration-context.json). Unused fields for a given
 * connector are simply omitted from the query string (apiClient drops
 * undefined params) — sending an extra field a connector doesn't use is
 * harmless (routing-only consolidation, same pattern as commitContext below).
 *
 * `unmatchedOnly` (-> `unmatched_only` query param): new filter, confirmed
 * live for the findings connectors (aif/gloc/lopc) — restricts `rows` to
 * those whose `asset_match_method` is still 'unmatched' against the equipment
 * identity graph. Not yet confirmed for pnid/documents/sap/timeseries; safe
 * to pass for any connector since apiClient drops it when undefined.
 *
 * `page`/`page_size` default to a single large page (1 / 500) because none
 * of the four review views implement server-driven pagination today — this
 * preserves the existing "fetch everything, page/search client-side"
 * behavior. A plant with more than 500 rows for a connector will be
 * truncated until real server-side pagination is built; flagged in
 * api-data/domain-configuration-context.json. The response now carries real
 * `pagination.has_more`/`next_cursor` metadata (confirmed for lopc) that
 * could drive server-side pagination in future — not wired up yet.
 *
 * @param {{ connector: string, plantCode: string, batchId?: string, files?: string,
 *   docTypes?: string, sourceFile?: string, table?: string, page?: number,
 *   pageSize?: number, jobId?: string, unmatchedOnly?: boolean }} opts
 */
export const getContext = ({
    connector, plantCode, batchId, files, docTypes, sourceFile, table,
    page = 1, pageSize = 500, jobId, unmatchedOnly,
} = {}) =>
    apiClient.get('/api/domain-configuration/context/get', {
        params: {
            connector,
            plant_code_id: plantCode,
            upload_batch_id: batchId,
            files,
            doc_types: docTypes,
            source_file: sourceFile,
            table,
            page,
            page_size: pageSize,
            pipeline_job_id: jobId,
            unmatched_only: unmatchedOnly,
        },
    }).then(unwrap);

// ── Commit (unified) ────────────────────────────────────────────────────────
/**
 * Commit reviewed context rows/tables for any connector through the single
 * unified commit router — `POST /context/commit`. Replaces the four
 * per-connector commit endpoints (commitPnidContext/commitDocsContext/
 * commitTsContext/commitSapContext); the backend keeps those alive but this
 * app now commits exclusively through this one path, with `connector`
 * selecting which internal flow runs.
 *
 * `connector` enum (2026-08-17): backend now documents SEVEN values — the
 * original 'pnid' | 'documents' | 'sap' | 'timeseries' PLUS the SAP-linked
 * feed connectors 'aif' | 'gloc' | 'lopc' (same native values added to the
 * upload endpoint the same day, see connectorsService.js + admin.constants.js
 * FEED_TYPES). NOT yet wired to any caller in this app — the feed upload flow
 * (useConfigModalActions.handleFeedSubmit) deliberately has no review screen,
 * so nothing here calls commitContext with a feed connector yet. Documented
 * for when that changes.
 *
 * `rows` (and each connector's other row/table payload field) is now OPTIONAL
 * — per the backend note "Omit `rows` and the backend commits the rows you
 * reviewed, you no longer have to POST thousands of rows back." Confirmed
 * live for `connector: 'gloc'` with a body of just `{ connector,
 * plant_code_id }`. Callers may still pass the full payload (see below) when
 * they have it; omitting it lets the backend commit whatever was already
 * staged via getContext/patchContextRows for that batch.
 *
 * This endpoint only consolidates ROUTING, not each connector's payload
 * shape — when a payload IS sent, `body` must carry whatever fields that
 * connector's commit previously required (plant_code/plant_code_id, batch_id,
 * and the connector's own row/table payload: `rows` for docs/timeseries,
 * `equipment_pid`/`equipment_connectivity` for pnid, `tables` for sap).
 * Confirmed live for `connector: 'timeseries'` (with rows) and
 * `connector: 'gloc'` (without rows) — see
 * api-data/domain-configuration-context.json for the full contract + open
 * questions on pnid/sap/documents/aif/lopc.
 */
export const commitContext = (connector, body) =>
    apiClient.post('/api/domain-configuration/context/commit', { ...body, connector }).then(unwrap);

/**
 * Persist reviewed context row edits or deletions for any connector through the single
 * unified rows PATCH router — `PATCH /context/rows`.
 *
 * `connector`: 'pnid' | 'documents' | 'sap' | 'timeseries'.
 * `body` must carry plant_code / plant_code_id, batch_id, and the updated row(s) array or deleted identifiers.
 */
export const patchContextRows = (connector, body) =>
    apiClient.patch('/api/domain-configuration/context/rows', { ...body, connector }).then(unwrap);

